// Turns the app schema, read from pg_catalog, into the committed TypeScript table types,
// and compares two renderings table by table. Pure: the same rows always give the same bytes.

export interface CatalogColumn {
  readonly table: string;
  readonly column: string;
  // pg_type.typname after domains are resolved to their base type.
  readonly type: string;
  // Element type name for an array column, otherwise null.
  readonly elementType: string | null;
  // Labels in sort order when the column (or its array element) is an enum.
  readonly enumLabels: readonly string[] | null;
  readonly nullable: boolean;
  // A default, an identity or a generated expression: an insert may leave it out.
  readonly hasDefault: boolean;
}

// Tables the migrate command owns; they hold no product data and are never queried by it.
export const BOOKKEEPING_TABLES: readonly string[] = ['pgmigrations', 'migration_checksums'];

const PRINT_WIDTH = 100;

// int8 maps to number: the pg parser for int8 is replaced so a value above 2^53 - 1 fails
// rather than losing precision.
const SCALARS: Readonly<Record<string, string>> = {
  bool: 'boolean',
  int2: 'number',
  int4: 'number',
  int8: 'number',
  float4: 'number',
  float8: 'number',
  numeric: 'string',
  text: 'string',
  varchar: 'string',
  bpchar: 'string',
  citext: 'string',
  name: 'string',
  uuid: 'string',
  inet: 'string',
  cidr: 'string',
  time: 'string',
  timetz: 'string',
  interval: 'string',
  // pgvector's text form, '[1,2,3]', until a parser is registered for it.
  vector: 'string',
  date: 'Date',
  timestamp: 'Date',
  timestamptz: 'Date',
  json: 'JsonValue',
  jsonb: 'JsonValue',
  bytea: 'Buffer',
};

const HEADER = `// Generated by \`pnpm --filter @drefyn/db check:types --write\` from the migrated app schema.
// Do not edit: check:types fails when this file and the schema disagree.

export type JsonValue =
  string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };

// The same shape as Kysely's ColumnType, so these types work there without importing it.
export interface ColumnType<Select, Insert = Select, Update = Select> {
  readonly __select__: Select;
  readonly __insert__: Insert;
  readonly __update__: Update;
}

// A column an insert may leave out because the database fills it in.
export type Generated<T> = ColumnType<T, T | undefined, T>;
`;

const quote = (label: string) => `'${label.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;

function baseType(column: CatalogColumn, name: string): string {
  if (column.enumLabels !== null) {
    return column.enumLabels.length === 0 ? 'never' : column.enumLabels.map(quote).join(' | ');
  }
  return SCALARS[name] ?? 'unknown';
}

function tsType(column: CatalogColumn): string {
  let type =
    column.elementType === null
      ? baseType(column, column.type)
      : `${wrapUnion(baseType(column, column.elementType))}[]`;
  if (column.nullable) type = `${type} | null`;
  return column.hasDefault ? `Generated<${type}>` : type;
}

const wrapUnion = (type: string) => (type.includes(' | ') ? `(${type})` : type);

// Identifiers Postgres allows but TypeScript does not are quoted.
const key = (name: string) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : quote(name));

const pascal = (table: string) =>
  table
    .split(/[^A-Za-z0-9]+/)
    .filter((part) => part !== '')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');

// Long unions are broken one member per line, as Prettier would print them.
function member(name: string, type: string): string {
  const line = `  ${key(name)}: ${type};`;
  if (line.length <= PRINT_WIDTH || !type.includes(' | ') || type.startsWith('Generated<')) {
    return line;
  }
  return [`  ${key(name)}:`, ...type.split(' | ').map((part) => `    | ${part}`)].join('\n') + ';';
}

function group(columns: readonly CatalogColumn[]): Map<string, CatalogColumn[]> {
  const tables = new Map<string, CatalogColumn[]>();
  for (const column of columns) {
    if (BOOKKEEPING_TABLES.includes(column.table)) continue;
    tables.set(column.table, [...(tables.get(column.table) ?? []), column]);
  }
  return new Map([...tables].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

function interfaceName(table: string, taken: ReadonlySet<string>): string {
  const base = `${pascal(table) || 'Unnamed'}Table`;
  return taken.has(base) ? `${base}${String(taken.size)}` : base;
}

// Columns arrive in table and attribute order; that order is kept.
export function renderSchema(columns: readonly CatalogColumn[]): string {
  const tables = group(columns);
  const names = new Map<string, string>();
  const parts = [HEADER];
  for (const [table, cols] of tables) {
    const name = interfaceName(table, new Set(names.values()));
    names.set(table, name);
    parts.push(
      `// app.${table}\nexport interface ${name} {\n${cols.map((c) => member(c.column, tsType(c))).join('\n')}\n}\n`,
    );
  }
  const entries = [...names].map(([table, name]) => `  ${key(table)}: ${name};`);
  parts.push(
    entries.length === 0
      ? '// Tables in schema app, keyed by name, as the search_path finds them.\nexport type Schema = Record<string, never>;\n'
      : `// Tables in schema app, keyed by name, as the search_path finds them.\nexport interface Schema {\n${entries.join('\n')}\n}\n`,
  );
  return parts.join('\n');
}

// The block for each table, keyed by its name, as renderSchema writes them.
function tableBlocks(text: string): Map<string, string> {
  const blocks = new Map<string, string>();
  for (const match of text.matchAll(
    /^\/\/ app\.(\S+)\n(export interface [^\n]*\{\n[\s\S]*?\n\}\n)/gm,
  )) {
    const [, table, block] = match;
    if (table !== undefined && block !== undefined) blocks.set(table, block);
  }
  return blocks;
}

export interface TypesDifference {
  // Tables whose types differ, are missing from the file, or are left over in it.
  readonly tables: readonly string[];
  // True when the tables agree but the rest of the file does not (an edit or an old header).
  readonly elsewhere: boolean;
}

export function compareRenderings(committed: string, expected: string): TypesDifference {
  const have = tableBlocks(committed);
  const want = tableBlocks(expected);
  const tables = [...new Set([...have.keys(), ...want.keys()])]
    .filter((table) => have.get(table) !== want.get(table))
    .sort();
  return { tables, elsewhere: tables.length === 0 && committed !== expected };
}
