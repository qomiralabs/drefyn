import { basename, resolve } from 'node:path';
import { runner, type MigrationBuilder, type RunnerOption } from 'node-pg-migrate';
import pg from 'pg';
import type { RecordedMigration } from './checksum.ts';
import type { MigrationConfig, SslMode } from './config.ts';
import {
  CHECKSUMS_TABLE,
  MIGRATE_LOCK_KEY,
  MIGRATIONS_SCHEMA,
  MIGRATIONS_TABLE,
} from './constants.ts';
import { MIGRATION_NAME, type MigrationFile } from './migration-file.ts';
import { MigrateError } from './outcome.ts';
import type { ConnectedRole, InvalidIndex, MigrateSession, RunRequest } from './run.ts';
import type { VectorExtension } from './prerequisites.ts';

const CONNECT_TIMEOUT_MS = 10_000;
// Checks and bookkeeping are small. The migrations themselves run with no statement timeout,
// because long index builds are legitimate; lock_timeout bounds their waits instead.
const CHECK_STATEMENT_TIMEOUT_MS = 30_000;
const LOCK_TIMEOUT = '2s';

// privilege_not_granted and privilege_not_revoked. Postgres only warns when a grant or
// revoke changes nothing, which in a migration means it does not do what it says.
const PRIVILEGE_WARNINGS = new Set(['01007', '01006']);

const MIGRATIONS = `${MIGRATIONS_SCHEMA}.${MIGRATIONS_TABLE}`;
const CHECKSUMS = `${MIGRATIONS_SCHEMA}.${CHECKSUMS_TABLE}`;

// Matches the tool's sort so a file it would never see cannot slip in beside ours.
const IGNORE_PATTERN = '(?![0-9]{13}_[a-z0-9]+(_[a-z0-9]+)*\\.sql$).*';

// A hash whose file is no longer recorded. A marked file's down leaves its hash for this,
// because deleting the hash first and crashing before the record goes would leave a record
// with no hash, and every later command would stop at exit 3.
const ORPHANS = `delete from ${CHECKSUMS} c where not exists (select from ${MIGRATIONS} m where m.name = c.name)`;

// Every invalid index in schema app, with whether a build for it is running now.
const INVALID_INDEXES = `
select i.relname as index, t.relname as table,
       exists (select from pg_stat_progress_create_index p where p.index_relid = i.oid) as building
  from pg_index x
  join pg_class i on i.oid = x.indexrelid
  join pg_class t on t.oid = x.indrelid
  join pg_namespace n on n.oid = i.relnamespace
 where n.nspname = '${MIGRATIONS_SCHEMA}' and not x.indisvalid
 order by i.relname`;

// Runs after a marked section and before its hash and record. A build that failed or was
// skipped over an invalid index raises here, so the file is never recorded as done.
const CHECK_INDEXES = `do $$
declare
  found text;
begin
  select string_agg(format('app.%s on app.%s', bad.index, bad.table)
           || case when bad.building then ' (a build is still in progress)' else '' end,
         ', ' order by bad.index)
    into found
    from (${INVALID_INDEXES}) bad;
  if found is not null then
    raise exception 'invalid indexes in schema app after this file ran: %', found;
  end if;
end $$;`;

// Owner only on every up and down: default privileges from the first migration would
// otherwise hand drefyn_app any bookkeeping table created later, for example after a drop.
const BOOKKEEPING = `
create table if not exists ${MIGRATIONS} (
  id integer generated by default as identity primary key,
  name varchar(255) not null,
  run_on timestamptz not null
);
create table if not exists ${CHECKSUMS} (
  name varchar(255) primary key,
  sha256 char(64) not null check (sha256 ~ '^[0-9a-f]{64}$'),
  recorded_at timestamptz not null default now()
);
revoke all on ${MIGRATIONS}, ${CHECKSUMS} from public, drefyn_app, drefyn_public_reader;
revoke all on sequence ${MIGRATIONS}_id_seq from public, drefyn_app, drefyn_public_reader;
${ORPHANS};
`;

function sslOption(mode: SslMode): pg.ClientConfig['ssl'] {
  switch (mode) {
    case 'disable':
      return false;
    case 'require':
      return { rejectUnauthorized: false };
    case 'verify-full':
      // Node checks the certificate chain and the host name by default.
      return { rejectUnauthorized: true };
  }
}

// Every field the URL gives. pg still fills any setting left empty from PG* variables, so
// createClient below is the only way a client is built.
export function clientConfig(config: MigrationConfig): pg.ClientConfig {
  const url = new URL(config.url);
  const password = decodeURIComponent(url.password);
  return {
    host: url.hostname.replace(/^\[(.*)\]$/, '$1'),
    port: url.port === '' ? 5432 : Number(url.port),
    user: decodeURIComponent(url.username),
    // A function, so neither PGPASSWORD nor a pgpass file can stand in, even when the URL
    // has no password.
    password: () => Promise.resolve(password),
    database: decodeURIComponent(url.pathname.slice(1)),
    ssl: sslOption(config.ssl),
    application_name: 'drefyn-migrate',
    connectionTimeoutMillis: CONNECT_TIMEOUT_MS,
    statement_timeout: CHECK_STATEMENT_TIMEOUT_MS,
    keepAlive: true,
  };
}

// pg reads PGOPTIONS, PGREPLICATION, PGBINARY and others for any setting the config leaves
// empty, and PGOPTIONS could set session settings for the migrate role. The constructor
// reads them synchronously, so they are hidden for exactly that call and put back.
export function createClient(config: MigrationConfig): pg.Client {
  const hidden = Object.entries(process.env).filter(([key]) => key.startsWith('PG'));
  for (const [key] of hidden) Reflect.deleteProperty(process.env, key);
  try {
    return new pg.Client(clientConfig(config));
  } finally {
    for (const [key, value] of hidden) process.env[key] = value;
  }
}

// The name and hash end up inside SQL text the tool runs, so both are checked again here
// even though the loader already did.
function recordSql(file: MigrationFile, direction: 'up' | 'down'): string | undefined {
  const name = file.name.replace(/\.sql$/, '');
  if (!MIGRATION_NAME.test(file.name) || !/^[0-9a-f]{64}$/.test(file.sha256)) {
    throw new MigrateError('failed', `refusing to record ${JSON.stringify(file.name)}`);
  }
  if (direction === 'down') {
    return file.transaction ? `delete from ${CHECKSUMS} where name = '${name}'` : undefined;
  }
  const insert = `insert into ${CHECKSUMS} (name, sha256) values ('${name}', '${file.sha256}')`;
  // A marked file repeats after a crash between its statements, so its hash may already be
  // there. A transactional file commits with its hash, so a leftover row there is an error.
  return file.transaction
    ? insert
    : `${insert} on conflict (name) do update set sha256 = excluded.sha256, recorded_at = now()`;
}

class PgSession implements MigrateSession {
  private readonly client: pg.Client;

  constructor(client: pg.Client) {
    this.client = client;
  }

  private async rows<R extends pg.QueryResultRow>(
    text: string,
    values: unknown[] = [],
  ): Promise<R[]> {
    const result = await this.client.query<R>(text, values);
    return result.rows;
  }

  async role(): Promise<ConnectedRole> {
    const [row] = await this.rows<{ name: string; superuser: boolean; bypass: boolean }>(
      `select current_user as name, r.rolsuper as superuser, r.rolbypassrls as bypass
         from pg_roles r where r.rolname = current_user`,
    );
    if (row === undefined) throw new MigrateError('failed', 'cannot read the connected role');
    return { name: row.name, superuser: row.superuser, bypassRls: row.bypass };
  }

  async vectorExtension(): Promise<VectorExtension | undefined> {
    const [row] = await this.rows<{ schema: string; version: string }>(
      `select n.nspname as schema, e.extversion as version
         from pg_extension e join pg_namespace n on n.oid = e.extnamespace
        where e.extname = 'vector'`,
    );
    return row;
  }

  async invalidIndexes(): Promise<InvalidIndex[]> {
    return this.rows<InvalidIndex>(INVALID_INDEXES);
  }

  async tryLock(): Promise<boolean> {
    const [row] = await this.rows<{ locked: boolean }>(
      'select pg_try_advisory_lock($1::bigint) as locked',
      [MIGRATE_LOCK_KEY.toString()],
    );
    return row?.locked === true;
  }

  async unlock(): Promise<void> {
    // A failed file can leave its transaction open and aborted, where no other statement runs.
    await this.rows('rollback');
    await this.rows('select pg_advisory_unlock($1::bigint)', [MIGRATE_LOCK_KEY.toString()]);
  }

  async setLockTimeout(): Promise<void> {
    await this.rows(`set lock_timeout = '${LOCK_TIMEOUT}'`);
  }

  async trackingTableProblem(): Promise<string | undefined> {
    const [row] = await this.rows<{ found: boolean; type: string | null }>(
      `select to_regclass($1) is not null as found,
              (select format_type(a.atttypid, a.atttypmod) from pg_attribute a
                where a.attrelid = to_regclass($1) and a.attname = 'run_on' and not a.attisdropped) as type`,
      [MIGRATIONS],
    );
    if (row?.found !== true || row.type === 'timestamp with time zone') return undefined;
    return [
      `${MIGRATIONS}.run_on is ${row.type ?? 'missing'}, not timestamp with time zone.`,
      'A plain node-pg-migrate run creates it that way. drefyn migrate never alters a table it did not create, so nothing was changed.',
    ].join('\n');
  }

  async history(): Promise<RecordedMigration[]> {
    const [found] = await this.rows<{ migrations: boolean; checksums: boolean }>(
      'select to_regclass($1) is not null as migrations, to_regclass($2) is not null as checksums',
      [MIGRATIONS, CHECKSUMS],
    );
    if (found?.migrations !== true) return [];
    // Same order the tool reads its history in.
    const rows = found.checksums
      ? await this.rows<{ name: string; sha256: string | null }>(
          `select m.name, c.sha256 from ${MIGRATIONS} m
             left join ${CHECKSUMS} c on c.name = m.name order by m.run_on, m.id`,
        )
      : await this.rows<{ name: string; sha256: null }>(
          `select name, null as sha256 from ${MIGRATIONS} order by run_on, id`,
        );
    return rows.map((r) => ({ name: r.name, sha256: r.sha256 ?? undefined }));
  }

  async ensureBookkeeping(): Promise<void> {
    // One query string runs as one implicit transaction.
    await this.rows(BOOKKEEPING);
  }

  async run(request: RunRequest): Promise<void> {
    const byPath = new Map(request.files.map((f) => [resolve(request.dir, f.name), f]));
    let current: string | undefined;

    const actions = (file: MigrationFile) => {
      const step = (direction: 'up' | 'down') => (pgm: MigrationBuilder) => {
        current = file.name;
        if (!file.transaction) pgm.noTransaction();
        pgm.sql(direction === 'up' ? file.up : file.down);
        // A failed transactional build rolls back and leaves no index, so only marked files
        // need the check.
        if (!file.transaction) pgm.sql(CHECK_INDEXES);
        const record = recordSql(file, direction);
        if (record !== undefined) pgm.sql(record);
      };
      return { up: step('up'), down: step('down') };
    };

    // The bytes hashed are the bytes run: the tool's own SQL parser and its jiti fallback
    // are never reached, and a path this run did not read is refused.
    const fromParsed = (filePaths: string[]) =>
      Promise.resolve(
        filePaths.map((path) => {
          const file = byPath.get(path);
          if (file === undefined) {
            throw new MigrateError(
              'failed',
              `${basename(path)} appeared after the folder was read`,
            );
          }
          return { id: path, filePaths: [path], actions: actions(file) };
        }),
      );

    const options: RunnerOption = {
      dbClient: this.guarded(),
      noLock: true,
      // Never `schema`: it would replace the database search_path.
      migrationsSchema: MIGRATIONS_SCHEMA,
      migrationsTable: MIGRATIONS_TABLE,
      dir: request.dir,
      ignorePattern: IGNORE_PATTERN,
      migrationLoaderStrategies: [{ extensions: ['.sql'], loader: fromParsed }],
      checkOrder: true,
      singleTransaction: false,
      direction: request.direction,
      count: request.count,
      logger: {
        info: (message: string) => {
          request.stdout.write(`${message}\n`);
        },
        warn: (message: string) => {
          request.stderr.write(`${message}\n`);
        },
        error: (message: string) => {
          request.stderr.write(`${message}\n`);
        },
      },
    };
    await this.rows('set statement_timeout = 0');
    try {
      await runner(options);
      await this.rows(ORPHANS);
    } catch (error) {
      // The tool wraps a loader error in its own; ours says more.
      if (error instanceof Error && error.cause instanceof MigrateError) throw error.cause;
      if (current === undefined || error instanceof MigrateError) throw error;
      const message = error instanceof Error ? error.message : 'unknown error';
      throw new MigrateError('failed', `${current} failed and was not recorded: ${message}`);
    }
  }

  // The runner's client, failing any statement that drew a privilege warning. The throw
  // comes before the file's COMMIT, so the file rolls back with its record and hash.
  private guarded(): pg.Client {
    const client = this.client;
    const warnings: string[] = [];
    client.on('notice', (notice) => {
      if (notice.code !== undefined && PRIVILEGE_WARNINGS.has(notice.code)) {
        warnings.push(notice.message ?? `warning ${notice.code}`);
      }
    });
    const query = async (...args: Parameters<pg.Client['query']>) => {
      const result: unknown = await (client.query as (...a: unknown[]) => Promise<unknown>)(
        ...args,
      );
      const warning = warnings.shift();
      if (warning !== undefined) {
        warnings.length = 0;
        throw new Error(`${warning}; a grant or revoke that changes nothing fails the migration`);
      }
      return result;
    };
    return Object.assign(Object.create(client) as pg.Client, { query });
  }

  async close(): Promise<void> {
    await this.client.end();
  }
}

// Wraps a connected client; the caller owns connecting it.
export function sessionFor(client: pg.Client): MigrateSession {
  return new PgSession(client);
}

export async function connectPg(config: MigrationConfig): Promise<MigrateSession> {
  const client = createClient(config);
  // A dropped connection surfaces through the query in flight; this keeps it from also
  // crashing the process as an unhandled event.
  client.on('error', () => undefined);
  await client.connect();
  return sessionFor(client);
}
