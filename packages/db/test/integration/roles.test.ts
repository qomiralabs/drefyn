import { expect, it } from 'vitest';
import { describeFailure, fixtureMigrations, migrate, migration } from './support/cli.ts';
import { databases } from './support/databases.ts';
import { describeWithStack } from './support/presence.ts';
import {
  CHECKSUMS,
  MIGRATIONS,
  extensionState,
  migrationState,
  query,
  session,
  tableExists,
} from './support/sql.ts';

const dbs = databases();

async function refused(url: string, sql: string): Promise<string> {
  try {
    await query(url, sql);
  } catch (error) {
    return (error as { code?: string }).code ?? 'no code';
  }
  return 'allowed';
}

describeWithStack('application role after the first migration', () => {
  it('cannot create tables in app', async () => {
    const db = await dbs.fresh('migrated');
    expect(await refused(db.app, 'create table app.sneaky (id int)')).toBe('42501');
    expect(await refused(db.app, 'create view app.sneaky as select 1')).toBe('42501');
    expect(
      await refused(
        db.app,
        'create function app.sneaky() returns int language sql as $$ select 1 $$',
      ),
    ).toBe('42501');
  });

  it('cannot drop or alter a table it did not create', async () => {
    const db = await dbs.fresh('migrated');
    await query(db.owner, 'create table app.owned (id int)');
    expect(await refused(db.app, 'drop table app.owned')).toBe('42501');
    expect(await refused(db.app, 'alter table app.owned add column x int')).toBe('42501');
    expect(await refused(db.app, 'truncate app.owned')).toBe('42501');
    expect(await tableExists(db.owner, 'app.owned')).toBe(true);
  });

  it('has CREATE on no schema and no CREATE or TEMP on the database', async () => {
    const db = await dbs.fresh('migrated');
    for (const role of ['drefyn_app', 'drefyn_public_reader']) {
      const schemas = await query<{ nspname: string }>(
        db.owner,
        `select nspname from pg_namespace where has_schema_privilege($1, oid, 'CREATE') order by nspname`,
        [role],
      );
      expect(schemas, role).toEqual([]);
      const database = await query(
        db.owner,
        `select has_database_privilege($1, current_database(), 'CREATE') as c,
                has_database_privilege($1, current_database(), 'TEMP') as t`,
        [role],
      );
      expect(database, role).toEqual([{ c: false, t: false }]);
    }
  });

  it('has usage on app and gets row privileges on new tables, nothing more', async () => {
    const db = await dbs.fresh('migrated');
    expect(
      await query(db.owner, `select has_schema_privilege('drefyn_app', 'app', 'USAGE') as u`),
    ).toEqual([{ u: true }]);
    await query(
      db.owner,
      'create table app.later (id bigint generated by default as identity, note text)',
    );
    const privileges = await query<{ privilege_type: string }>(
      db.owner,
      `select privilege_type from information_schema.role_table_grants
        where grantee = 'drefyn_app' and table_schema = 'app' and table_name = 'later'
        order by privilege_type`,
    );
    expect(privileges.map((p) => p.privilege_type)).toEqual([
      'DELETE',
      'INSERT',
      'SELECT',
      'UPDATE',
    ]);
    const sequence = await query(
      db.owner,
      `select has_sequence_privilege('drefyn_app', 'app.later_id_seq', 'USAGE') as usage,
              has_sequence_privilege('drefyn_app', 'app.later_id_seq', 'SELECT') as sel,
              has_sequence_privilege('drefyn_app', 'app.later_id_seq', 'UPDATE') as upd`,
    );
    expect(sequence).toEqual([{ usage: true, sel: true, upd: false }]);
  });

  it('gets the reader nothing by default', async () => {
    const db = await dbs.fresh('migrated');
    await query(db.owner, 'create table app.later (id int)');
    expect(
      await query(
        db.owner,
        `select has_table_privilege('drefyn_public_reader', 'app.later', 'SELECT') as s`,
      ),
    ).toEqual([{ s: false }]);
  });

  // The app role must not be able to rewrite what has run or its recorded hashes.
  it('cannot read or change the migration records', async () => {
    const db = await dbs.fresh('migrated');
    for (const table of [MIGRATIONS, CHECKSUMS]) {
      expect(await tableExists(db.owner, table), table).toBe(true);
      for (const privilege of ['SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE']) {
        expect(
          await query(db.owner, `select has_table_privilege('drefyn_app', $1, $2) as p`, [
            table,
            privilege,
          ]),
          `${table} ${privilege}`,
        ).toEqual([{ p: false }]);
      }
    }
  });
});

describeWithStack('tenant context functions', () => {
  const ORG = '01a14984-4476-77ce-9335-2c3c3a59aa8b';
  const PROJECT = '01a14984-4476-77ce-9335-2c3c3a59aa8c';

  it('are stable, security invoker and owned by drefyn_owner', async () => {
    const db = await dbs.fresh('migrated');
    const rows = await query(
      db.owner,
      `select proname, prosecdef, provolatile, pg_get_userbyid(proowner) as owner,
              pg_get_function_result(oid) as result
         from pg_proc where pronamespace = 'app'::regnamespace
          and proname in ('current_org', 'current_project') order by proname`,
    );
    expect(rows).toEqual([
      {
        proname: 'current_org',
        prosecdef: false,
        provolatile: 's',
        owner: 'drefyn_owner',
        result: 'uuid',
      },
      {
        proname: 'current_project',
        prosecdef: false,
        provolatile: 's',
        owner: 'drefyn_owner',
        result: 'uuid',
      },
    ]);
  });

  it('read null without context, the ids inside a transaction, and null again after commit', async () => {
    const db = await dbs.fresh('migrated');
    const client = await session(db.app);
    try {
      const read = async () =>
        (
          await client.query<{ org: string | null; project: string | null }>(
            'select app.current_org() as org, app.current_project() as project',
          )
        ).rows[0];
      expect(await read()).toEqual({ org: null, project: null });
      await client.query('begin');
      await client.query("select set_config('drefyn.organization_id', $1, true)", [ORG]);
      await client.query("select set_config('drefyn.project_id', $1, true)", [PROJECT]);
      expect(await read()).toEqual({ org: ORG, project: PROJECT });
      await client.query('commit');
      // The setting is left as an empty string on a reused connection, which must read as null.
      expect(await read()).toEqual({ org: null, project: null });
    } finally {
      await client.end();
    }
  });
});

describeWithStack('migrations run as drefyn_owner only', () => {
  it.each([
    ['drefyn_app', 'app'],
    ['drefyn_public_reader', 'reader'],
  ] as const)('refuses to run as %s and applies nothing', async (role, key) => {
    const db = await dbs.fresh('base');
    const result = await migrate(['migrate', 'up'], { url: db[key] });
    expect(result.code, describeFailure(result)).toBe(1);
    expect(result.stderr).toContain('drefyn_owner');
    expect(result.stderr).toContain(role);
    expect(await migrationState(db.owner)).toBeNull();
  });
});

describeWithStack('migrations cannot create or change extensions', () => {
  it.each([
    ['create extension if not exists pg_trgm schema extensions;', /permission denied/i],
    ['create extension if not exists pg_trgm schema app;', /permission denied/i],
    ['alter extension vector update;', /must be owner/i],
    ['alter extension vector set schema app;', /must be owner/i],
    ['drop extension vector;', /must be owner/i],
    ['drop schema extensions cascade;', /must be owner/i],
    [
      'create function extensions.probe() returns int language sql as $$ select 1 $$;',
      /permission denied/i,
    ],
    ['create table extensions.probe (id int);', /permission denied/i],
    [
      'grant create on schema extensions to drefyn_app;',
      /no privileges were granted|permission denied/i,
    ],
  ])('refuses %s, exits 1 and changes nothing', async (statement, message) => {
    const db = await dbs.fresh('base');
    const extensions = await extensionState(db.owner);
    const dir = fixtureMigrations({
      '9000000000001_extension.sql': migration(statement, 'select 1;'),
    });
    const result = await migrate(['migrate', 'up'], { url: db.owner, migrationsDir: dir });
    expect(result.code, describeFailure(result)).toBe(1);
    expect(result.stdout + result.stderr).toMatch(message);
    expect((await migrationState(db.owner))?.applied ?? []).not.toContain(
      '9000000000001_extension',
    );
    expect(await extensionState(db.owner)).toEqual(extensions);
  });
});

// Default privileges from the first migration would hand drefyn_app any bookkeeping table
// the owner creates later, so the wrapper revokes everything on every up and down.
describeWithStack('migration bookkeeping stays owner only', () => {
  const OTHERS = 'public, drefyn_app, drefyn_public_reader';

  // Every grantee on the relation other than its owner; 'public' for the public pseudo role.
  async function grantees(url: string, relation: string): Promise<string[]> {
    const rows = await query<{ grantee: string }>(
      url,
      `select distinct case when a.grantee = 0 then 'public' else pg_get_userbyid(a.grantee) end as grantee
         from pg_class c cross join lateral aclexplode(c.relacl) a
        where c.oid = to_regclass($1) and a.grantee <> c.relowner
        order by 1`,
      [relation],
    );
    return rows.map((r) => r.grantee);
  }

  async function sequenceOf(url: string): Promise<string> {
    const rows = await query<{ seq: string | null }>(
      url,
      `select pg_get_serial_sequence($1, 'id') as seq`,
      [MIGRATIONS],
    );
    const seq = rows[0]?.seq;
    if (seq == null) throw new Error(`${MIGRATIONS}.id has no sequence`);
    return seq;
  }

  async function leak(url: string): Promise<void> {
    await query(url, `grant select on ${MIGRATIONS}, ${CHECKSUMS} to drefyn_app`);
    await query(
      url,
      `grant select, insert, update, delete, truncate on ${MIGRATIONS}, ${CHECKSUMS} to ${OTHERS}`,
    );
    await query(
      url,
      `grant usage, select, update on sequence ${await sequenceOf(url)} to ${OTHERS}`,
    );
  }

  async function expectOwnerOnly(url: string): Promise<void> {
    for (const relation of [MIGRATIONS, CHECKSUMS, await sequenceOf(url)]) {
      expect(await grantees(url, relation), relation).toEqual([]);
    }
    for (const table of [MIGRATIONS, CHECKSUMS]) {
      for (const privilege of ['SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE']) {
        expect(
          await query(url, `select has_table_privilege('drefyn_app', $1, $2) as p`, [
            table,
            privilege,
          ]),
          `${table} ${privilege}`,
        ).toEqual([{ p: false }]);
      }
    }
  }

  it('leaves no privilege for others on a fresh up', async () => {
    const db = await dbs.fresh('base');
    const up = await migrate(['migrate', 'up'], { url: db.owner });
    expect(up.code, describeFailure(up)).toBe(0);
    await expectOwnerOnly(db.owner);
  });

  it('revokes grants the owner added by hand on the next up, even with nothing to apply', async () => {
    const db = await dbs.fresh('migrated');
    await leak(db.owner);
    expect(await grantees(db.owner, MIGRATIONS)).toContain('drefyn_app');

    const up = await migrate(['migrate', 'up'], { url: db.owner });
    expect(up.code, describeFailure(up)).toBe(0);
    await expectOwnerOnly(db.owner);
  });

  it('revokes them on down too', async () => {
    const db = await dbs.fresh('migrated');
    const dir = fixtureMigrations({
      '9000000000001_widgets.sql': migration(
        'create table app.widgets (id int);',
        'drop table app.widgets;',
      ),
    });
    expect((await migrate(['migrate', 'up'], { url: db.owner, migrationsDir: dir })).code).toBe(0);
    await leak(db.owner);

    const down = await migrate(['migrate', 'down'], { url: db.owner, migrationsDir: dir });
    expect(down.code, describeFailure(down)).toBe(0);
    await expectOwnerOnly(db.owner);
  });

  // Status is read only, so it reports and leaves even a bad grant for up or down to fix.
  it('status changes no grant', async () => {
    const db = await dbs.fresh('migrated');
    await leak(db.owner);
    const before = await grantees(db.owner, MIGRATIONS);
    const status = await migrate(['migrate', 'status'], { url: db.owner });
    expect(status.code, describeFailure(status)).toBe(0);
    expect(await grantees(db.owner, MIGRATIONS)).toEqual(before);
  });

  it('records run_on as timestamp with time zone', async () => {
    const db = await dbs.fresh('migrated');
    expect(
      await query(
        db.owner,
        `select format_type(atttypid, atttypmod) as type from pg_attribute
          where attrelid = to_regclass($1) and attname = 'run_on' and not attisdropped`,
        [MIGRATIONS],
      ),
    ).toEqual([{ type: 'timestamp with time zone' }]);
  });
});
